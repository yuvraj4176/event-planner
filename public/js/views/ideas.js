import { h } from '../dom.js';
import { icon } from '../icons.js';

export const SOURCE_LABELS = Object.freeze({
  ai: 'Generated by the Gemini AI assistant from your details.',
  builtin: 'Selected by the built-in planner using your theme, guest count and budget.',
});

export function groupByCategory(items) {
  const groups = new Map();
  for (const item of items) {
    if (!groups.has(item.category)) groups.set(item.category, []);
    groups.get(item.category).push(item);
  }
  return [...groups].map(([category, entries]) => ({ category, entries }));
}

function ideaCard(idea) {
  return h(
    'li',
    { class: 'idea' },
    h('h5', { text: idea.title }),
    h('p', { text: idea.detail }),
    Array.isArray(idea.matchedOn) && idea.matchedOn.length > 0
      ? h('p', { class: 'idea-match', text: `Matches your interests: ${idea.matchedOn.join(', ')}` })
      : null,
  );
}

export function createIdeasView({ ideas, aiEnabled, onRequestAi }) {
  const sourceNote = h('p', { class: 'source-note' });
  const list = h('div', { class: 'idea-groups' });
  const message = h('p', { class: 'hint', role: 'status' });
  const button = aiEnabled
    ? h('button', { type: 'button', class: 'button button-secondary' }, icon('sparkles'), h('span', { text: 'Generate ideas with AI' }))
    : null;

  function setIdeas(next) {
    sourceNote.textContent = SOURCE_LABELS[next.source] ?? SOURCE_LABELS.builtin;
    list.replaceChildren(
      ...groupByCategory(next.items).map((group) =>
        h('section', { class: 'idea-group' }, h('h4', { text: group.category }), h('ul', { class: 'idea-list' }, group.entries.map(ideaCard))),
      ),
    );
  }

  function setBusy(busy, text = '') {
    if (button) {
      button.disabled = busy;
      button.setAttribute('aria-busy', String(busy));
    }
    message.textContent = text;
  }

  if (button) button.addEventListener('click', () => onRequestAi());

  setIdeas(ideas);

  const element = h(
    'div',
    { class: 'ideas-view' },
    h('h3', { text: 'Ideas for your event' }),
    sourceNote,
    aiEnabled
      ? h('div', { class: 'action-row' }, button, message)
      : h('p', { class: 'hint', text: 'AI generated ideas are switched off on this server. The built-in planner provides these suggestions.' }),
    list,
  );

  return { element, setIdeas, setBusy, sourceNote, message };
}
